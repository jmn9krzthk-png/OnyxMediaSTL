#!/usr/bin/env python3
"""Write prototype/lp/ads-config.js from environment variables.

Runs inside tools/build_site.py and as the Netlify build command, so the Google Ads
IDs can be set in Netlify (Site configuration > Environment variables) without
being typed into the code:

  NEXT_PUBLIC_GOOGLE_ADS_ID                 AW-XXXXXXXXX
  NEXT_PUBLIC_GOOGLE_ADS_CONVERSION_LABEL   label of the "form submit" conversion
  NEXT_PUBLIC_GOOGLE_ADS_CALL_LABEL         label of the "click to call" conversion

Empty or malformed values are written as "", and the pages then skip the Google tag.
"""
import json, os, pathlib, re

OUT = pathlib.Path(__file__).resolve().parent.parent / "prototype" / "lp" / "ads-config.js"

def _get(name, pattern):
    v = os.environ.get(name, "").strip()
    return v if re.fullmatch(pattern, v) else ""

def main():
    cfg = {
        "id": _get("NEXT_PUBLIC_GOOGLE_ADS_ID", r"AW-\d{6,15}"),
        "label": _get("NEXT_PUBLIC_GOOGLE_ADS_CONVERSION_LABEL", r"[A-Za-z0-9_-]{1,64}"),
        "callLabel": _get("NEXT_PUBLIC_GOOGLE_ADS_CALL_LABEL", r"[A-Za-z0-9_-]{1,64}"),
    }
    OUT.parent.mkdir(parents=True, exist_ok=True)
    OUT.write_text("/* Generated by tools/lp_config.py from env vars. Do not edit. */\n"
                   f"window.ONYX_ADS={json.dumps(cfg)};\n")
    print("ads-config:", {k: ("set" if v else "empty") for k, v in cfg.items()})

if __name__ == "__main__":
    main()
